_DIAGNOSTIC_INTENT = re.compile(
    r"неисправ|полом|сломал|повред|подшип|причин|из-за чего|что случил|стуч|стук|шум|нагрев|перегрев|"
    r"теч[её]т|течь|задевают|задевает|цепля|потер[ия]|валк|развернут|разв[её]рт|не работает|"
    r"не поднима|не вращ|не крут|вибрац|греется|граблин.*земл|редуктор",
    re.IGNORECASE,
)


def is_diagnostic_question(question: str) -> bool:
    return bool(_DIAGNOSTIC_INTENT.search(normalize(question)))


def match_manual_diagnosis(question: str) -> dict[str, Any] | None:
    normalized_question = normalize(question)
    candidates: list[tuple[int, dict[str, Any]]] = []
    for case in CASES:
        matches = [pattern for pattern in case["patterns"] if normalize(pattern) in normalized_question]
        if matches:
            candidates.append((max(map(len, matches)), case))
    if not candidates:
        return None
    candidates.sort(key=lambda item: item[0], reverse=True)
    # Avoid a confident result if the question contains two distinct symptoms.
    top_score = candidates[0][0]
    top = [case for score, case in candidates if score == top_score]
    if len(top) != 1:
        return None
    return top[0]



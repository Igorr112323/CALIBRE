def _hardware_hypothesis(part: dict[str, Any]) -> tuple[str, str] | None:
    name = part["name"].casefold()
    figure = part["figure"]
    if "болт" in name:
        return ("Вероятно, стягивает/крепит сопряжённые детали указанного узла. По каталожной строке нельзя установить момент затяжки или точный стык.", "medium")
    if "гайка" in name:
        return ("Вероятно, образует резьбовое соединение с соответствующим болтом. Точное место и способ затяжки по этой позиции не определяются.", "medium")
    if "шайба стопорная" in name or ("шайба" in name and "т" in name and "65г" in name):
        return ("Вероятно, устанавливается в болтовом соединении как стопорный/пружинящий элемент для снижения риска самоотвинчивания; конкретное соединение не установлено.", "medium")
    if "шайба" in name:
        return ("Вероятно, распределяет усилие затяжки и/или задаёт зазор между сопряжёнными деталями. Конкретное место установки по общему виду не всегда различимо.", "medium")
    if "шплинт" in name:
        return ("Вероятно, фиксирует палец/ось или гайку от осевого выпадения/отвинчивания; точная фиксируемая деталь на общем виде может быть неразличима.", "medium")
    if "ось" in name:
        return ("Вероятно, служит пальцем шарнирного или крепёжного соединения в показанном узле; конкретную пару деталей каталог не называет.", "low")
    if "кольцо" in name:
        return ("Вероятно, удерживает или позиционирует сопряжённые детали в осевом направлении; точная функция зависит от места установки.", "low")
    if "масленка" in name:
        return ("Вероятно, является точкой подачи смазки к сочленению/подшипниковому узлу.", "high")
    return None


def assess_part(part: dict[str, Any]) -> dict[str, Any] | None:
    """Return a clearly labelled inference for a non-manual-confirmed part."""
    if part.get("individual_role_status") == "explicit_or_component_named_in_manual":
        return None
    hypothesis = HYPOTHESES.get((part["figure"], part["position"]))
    if hypothesis is None:
        hypothesis = _hardware_hypothesis(part)
    if hypothesis is None:
        hypothesis = (
            "По названию и месту в сборочном рисунке деталь, вероятно, соединяет, поддерживает или позиционирует соседние элементы этого узла; более точную функцию без спецификации производителя подтвердить нельзя.",
            "low",
        )
    text, confidence = hypothesis
    return {
        "status": "engineering_hypothesis",
        "manufacturer_confirmed": False,
        "hypothesis": text,
        "basis": "Инженерная интерпретация названия/обозначения и положения детали на взрыв-схеме; это не подтверждение производителя и не дословное утверждение руководства.",
        "confidence": confidence,
        "drawing_pages": part.get("figure_pages", []),
        "drawing_figure": part.get("figure"),
        "basis_kind": "catalog_name_and_exploded_view",
    }
